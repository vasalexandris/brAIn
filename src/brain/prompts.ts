function dimensionList(): string {
  const appraised = new Set([...PERCEPTION_KEYS, ...INNER_KEYS]);
  return DIMENSIONS.filter((d) => appraised.has(d.key)).map((d) => `${d.key} — ${d.label}: ${d.hint}`).join("\n");
}

export function perceivePrompt(input: {
  values: BrainValues;
  impression: string;
  history: ChatMessage[];
  message: string;
  time: TimeSense;
}): string {
  return `Δείκτες (κλειδί — όνομα: τι μετρά). Όσοι αρχίζουν με p_ είναι δείκτες αντίληψης, οι υπόλοιποι εσωτερικοί:
${dimensionList()}

Τρέχουσα κατάσταση του εγκεφάλου:
${describeState(input.values, ["emotion", "mood", "trait", "relationship"])}

Η εντύπωσή του για τον συνομιλητή ως τώρα: ${input.impression || "(καμία ακόμη)"}

Χρόνος: ${describeTime(input.time)}

Πρόσφατη συζήτηση:
${transcript(input.history)}

Νέο μήνυμα του συνομιλητή:
<μήνυμα>
${input.message}
</μήνυμα>`;
}

