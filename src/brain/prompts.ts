/**
 * Τα prompts των τριών σταδίων: αντίληψη → απόκριση → αναστοχασμός.
 */
import { CATEGORY_LABELS, DIMENSIONS, EMOTION_KEYS, DIMENSION_BY_KEY, type Category } from "./dimensions";
import { MEMORY_KIND_LABELS, type Recalled } from "./memory";
import type { BrainValues } from "./state";
import type { ChatMessage } from "@/llm/types";

function intensity(v: number): string {
  if (v < 10) return "ανύπαρκτο";
  if (v < 30) return "χαμηλό";
  if (v < 55) return "μέτριο";
  if (v < 80) return "έντονο";
  return "κυριαρχεί";
}

/** Η κατάσταση σε μορφή που διαβάζει το μοντέλο. Με ★ όσα έχουν ξεφύγει από το φυσιολογικό τους. */
export function describeState(values: BrainValues, categories?: Category[]): string {
  const cats = categories ?? (Object.keys(CATEGORY_LABELS) as Category[]);
  return cats
    .map((cat) => {
      const lines = DIMENSIONS.filter((d) => d.category === cat).map((d) => {
        const v = Math.round(values[d.key]);
        const shifted = Math.abs(v - d.baseline) >= 15 ? " ★" : "";
        return `- ${d.label}: ${v} (${intensity(v)})${shifted}`;
      });
      return `${CATEGORY_LABELS[cat]}:\n${lines.join("\n")}`;
    })
    .join("\n\n");
}

function transcript(history: ChatMessage[]): string {
  if (!history.length) return "(καμία — είναι το πρώτο μήνυμα)";
  return history.map((m) => `${m.role === "user" ? "Συνομιλητής" : "Εγώ"}: ${m.content}`).join("\n");
}

function age(from: Date, now: Date): string {
  const min = Math.round((now.getTime() - from.getTime()) / 60000);
  if (min < 60) return "πριν από λίγο";
  if (min < 60 * 24) return `πριν από ${Math.round(min / 60)} ώρες`;
  const days = Math.round(min / (60 * 24));
  return days === 1 ? "χθες" : `πριν από ${days} μέρες`;
}

