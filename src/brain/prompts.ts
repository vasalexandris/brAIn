export function reflectPrompt(input: {
  values: BrainValues;
  impression: string;
  message: string;
  reply: string;
}): string {
  const emotions = EMOTION_KEYS.map((k) => `${k} — ${DIMENSION_BY_KEY[k].label}`).join(", ");
  return `Κλειδιά συναισθημάτων: ${emotions}

Κατάσταση του εγκεφάλου τη στιγμή της απάντησης:
${describeState(input.values, ["emotion", "relationship"])}

Τρέχουσα εντύπωση για τον συνομιλητή: ${input.impression || "(καμία ακόμη)"}

Ο συνομιλητής είπε:
<μήνυμα>
${input.message}
</μήνυμα>

Ο εγκέφαλος απάντησε:
<απάντηση>
${input.reply}
</απάντηση>`;
}
