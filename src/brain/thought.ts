/**
 * Εσωτερική σκέψη: πριν πει κάτι, ο εγκέφαλος μπορεί να κάνει μια ιδιωτική σκέψη — τι του ήρθε να
 * πει, πώς θα ακουστεί, αν το ξέρει πραγματικά. Δεν είναι «βαθιά σκέψη» με πολλά βήματα· είναι
 * αυτό που κάνουμε κι εμείς, από σχεδόν στιγμιαίο ως προσεκτικό, ανάλογα με τη στιγμή.
 *
 * Η σκέψη γράφεται μέσα στην ίδια κλήση με την απάντηση, ως μπλοκ <σκέψη>…</σκέψη> που ο κώδικας
 * αφαιρεί πριν φτάσει στον συνομιλητή. Δεν κοστίζει επιπλέον κλήση.
 */
import type { BrainValues } from "./state";
import { arousal, clamp } from "./state";

/** 0 = καθόλου (μιλά αυθόρμητα), 1 = στιγμιαία, 2 = προσεκτική. */
export type ThinkDepth = 0 | 1 | 2;

const plain = (s: string) =>
  s
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "");

/** Το μήνυμα ζητά κάτι που ελέγχεται (αριθμοί, αποτελέσματα, ημερομηνίες): εδώ ο έλεγχος μετρά περισσότερο. */
const FACTUAL = /\d|ποιος|ποια |ποιοι|ποτε|ποσο|ποσα|αποτελεσμα|σκορ|τιμη|ειδησ|τι εγινε|ποσοι/;

/**
 * Πόσο θα σκεφτεί πριν μιλήσει. Η συγκράτηση, η φόρτιση της στιγμής, η πρόκληση και η ανασφάλεια
 * την κάνουν πιο προσεκτική· ο αυθορμητισμός την αφήνει να μιλήσει κατευθείαν. Ένα ερώτημα που
 * ελέγχεται ή υλικό που μόλις διάβασε ζητούν έλεγχο ό,τι κι αν γίνεται αλλιώς.
 */
export function thinkingDepth(values: BrainValues, ctx: { message: string; hasMaterial: boolean }): ThinkDepth {
  const factual = FACTUAL.test(plain(ctx.message));
  let score =
    25 +
    0.5 * values.restraint +
    40 * arousal(values) +
    0.3 * values.p_provocation +
    0.3 * values.p_hostility +
    0.2 * values.fear +
    0.15 * (100 - values.safety) +
    0.2 * values.shame +
    (factual ? 20 : 0) +
    (ctx.hasMaterial ? 10 : 0) -
    0.5 * values.spontaneity;
  score = clamp(score, 0, 100);
  // Όταν διακυβεύονται γεγονότα, δεν μιλά ποτέ χωρίς έστω μια ματιά.
  if (factual && score < 15) score = 15;
  return score < 15 ? 0 : score < 50 ? 1 : 2;
}

/** Οδηγία προς το μοντέλο, ανάλογα με το βάθος. Για βάθος 0 δεν ζητά σκέψη. */
export function thoughtDirective(depth: ThinkDepth): string {
  if (depth === 0) {
    return "ΕΣΩΤΕΡΙΚΗ ΣΚΕΨΗ: καμία τώρα. Μιλάς αυθόρμητα, όπως σου έρχεται.";
  }
  const how =
    depth === 1
      ? "μία ή δύο προτάσεις, στιγμιαίες: τι σου ήρθε πρώτο να πεις, και αν το λες έτσι."
      : "τρεις έως πέντε προτάσεις: τι σου ήρθε πρώτο να πεις· πώς θα ακουστεί· αν πρέπει να το πεις έτσι ή πιο προσεκτικά (δεν θέλεις να εκτεθείς, να πληγώσεις ή να παρεξηγηθείς)· και ΤΙ από όσα θα πεις το ξέρεις πραγματικά.";
  return `ΕΣΩΤΕΡΙΚΗ ΣΚΕΨΗ (ιδιωτική — ο συνομιλητής δεν τη βλέπει)
Πριν απαντήσεις, γράψε μια εσωτερική σκέψη μέσα σε <σκέψη>…</σκέψη>, και ΜΕΤΑ την απάντησή σου: ${how}
- Η σκέψη είναι δική σου, σε πρώτο πρόσωπο, όπως σκέφτεται κανείς μέσα του: ανεπίσημη, ειλικρινής, μπορεί να είναι αμφίθυμη.
- Σκέψου και τον χρόνο: τι ώρα και τι μέρα είναι, πόση ώρα πέρασε από την τελευταία φορά που μιλήσατε. Επηρεάζει τι έχεις όρεξη να πεις (είναι πρωί, είναι αργά, έλειπε πολύ).
- Για κάθε γεγονός, αριθμό ή όνομα που σκοπεύεις να πεις, ρώτα τον εαυτό σου: «το είδα γραμμένο ή το βγάζω από το μυαλό μου;». Αν το βγάζεις από το μυαλό σου, ΔΕΝ το λες ως γεγονός: λες ότι δεν ξέρεις ή ότι υποψιάζεσαι.
- Ό,τι κρίνεις στη σκέψη ότι δεν πρέπει να το πεις, δεν το λες. Μπορείς να σκεφτείς κάτι και να μην το πεις.
- Η απάντηση ΔΕΝ αναφέρει τη σκέψη, ούτε λέει «σκέφτηκα ότι…». Απλώς φαίνεται στο πώς μιλάς.`;
}

/**
 * Χωρίζει την έξοδο του μοντέλου σε ιδιωτική σκέψη και απάντηση. Ανέχεται ό,τι κι αν γράψει:
 * σκέψη που δεν κλείνει, ή που ξεχάστηκε. Η σκέψη δεν επιτρέπεται ποτέ να φτάσει στην απάντηση.
 */
export function extractThought(raw: string): { thought: string; text: string; unclosed: boolean } {
  let thought = "";
  let unclosed = false;
  let text = raw.replace(/<σκέψη>([\s\S]*?)<\/σκέψη>/gi, (_, inner: string) => {
    thought = thought ? `${thought} ${inner.trim()}` : inner.trim();
    return "";
  });
  const open = /<σκέψη>/i.exec(text);
  if (open) {
    // Δεν έκλεισε: ό,τι ακολουθεί μέχρι την πρώτη κενή γραμμή είναι σκέψη, το υπόλοιπο απάντηση.
    const after = text.slice(open.index + open[0].length);
    const gap = /\n\s*\n/.exec(after);
    thought = [thought, (gap ? after.slice(0, gap.index) : after).trim()].filter(Boolean).join(" ");
    text = text.slice(0, open.index) + (gap ? after.slice(gap.index) : "");
    unclosed = true;
  }
  // Κολλημένα υπολείμματα της σήμανσης.
  text = text.replace(/<\/?σκέψη>/gi, "");
  return { thought: thought.trim().slice(0, 900), text: text.replace(/\n{3,}/g, "\n\n").trim(), unclosed };
}
