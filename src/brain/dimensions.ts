/**
 * Ο κατάλογος των "δεικτών" του εγκεφάλου.
 *
 * Κάθε δείκτης είναι μια μπάρα 0–100 με:
 *  - baseline:    την έμφυτη τιμή ηρεμίας, στην οποία επιστρέφει με τον χρόνο
 *  - halfLifeMin: σε πόσα λεπτά χάνει τη μισή απόσταση από το baseline
 *  - maxStep:     πόσο το πολύ μπορεί να μετακινηθεί από ένα μόνο μήνυμα
 *
 * Για να προστεθεί νέο γνώρισμα αρκεί μια νέα γραμμή εδώ: η αξιολόγηση,
 * η δυναμική και τα prompts το παίρνουν αυτόματα.
 */

export type Category =
  | "perception" // τι αντιλαμβάνεται στον συνομιλητή αυτή τη στιγμή
  | "emotion" // δικά του συναισθήματα (γρήγορα)
  | "mood" // διάθεση (αργή)
  | "drive" // ορμές / ορέξεις
  | "trait" // γνωρίσματα χαρακτήρα (πολύ αργά)
  | "value" // αξίες: τι θεωρεί σωστό (σχεδόν αμετακίνητες)
  | "self" // εαυτός: πώς στέκεται απέναντι στον εαυτό του (υπολογίζεται)
  | "relationship" // στάση απέναντι στον συγκεκριμένο άνθρωπο (μόνιμη)
  | "core" // βασικός τόνος: σύνοψη όλων των συναισθημάτων σε δύο άξονες (υπολογίζεται)
  | "time" // αίσθηση του χρόνου (υπολογίζεται από το ρολόι, όχι από το μοντέλο)
  | "urge"; // παρορμήσεις: τι θέλει να ΚΑΝΕΙ τώρα (υπολογίζονται από τους άλλους δείκτες)

export interface Dimension {
  key: string;
  label: string;
  category: Category;
  baseline: number;
  halfLifeMin: number;
  maxStep: number;
  hint: string;
}

