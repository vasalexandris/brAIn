const MIN = 1;
const HOUR = 60;
const DAY = 24 * HOUR;

type Row = [key: string, label: string, baseline: number, hint: string];

function group(category: Category, halfLifeMin: number, maxStep: number, rows: Row[]): Dimension[] {
  return rows.map(([key, label, baseline, hint]) => ({
    key,
    label,
    category,
    baseline,
    halfLifeMin,
    maxStep,
    hint,
  }));
}

